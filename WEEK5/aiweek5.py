import random
import math


def calculate_cost(state):
    cost = 0
    n = len(state)

    for i in range(n):
        for j in range(i + 1, n):
            if (state[i] == state[j] or
                abs(state[i] - state[j]) == abs(i - j)):
                cost += 1

    return cost


def simulated_annealing():
    n = 8
    temperature = 100.0
    cooling_rate = 0.995
    max_iterations = 10000

    # Random initial state: one queen per column
    state = [random.randint(1, n) for _ in range(n)]
    current_cost = calculate_cost(state)

    for step in range(max_iterations):
        print("Step:", step,
              "State:", state,
              "Cost:", current_cost)

        if current_cost == 0:
            print("Goal state reached!")
            return state

        # Stop if temperature becomes too low
        if temperature < 0.0001:
            break

        # Generate a random neighbor
        neighbor = state[:]
        col = random.randrange(n)

        new_row = random.randint(1, n)
        while new_row == neighbor[col]:
            new_row = random.randint(1, n)

        neighbor[col] = new_row
        new_cost = calculate_cost(neighbor)

        delta = new_cost - current_cost

        # Accept better moves or probabilistically accept worse moves
        if delta <= 0 or random.random() < math.exp(-delta / temperature):
            state = neighbor
            current_cost = new_cost

        # Cool down
        temperature *= cooling_rate

    print("No solution found in this run.")
    return None


# Main program with random restarts
solution = None

for attempt in range(100):
    print("\nAttempt:", attempt + 1)
    solution = simulated_annealing()

    if solution is not None:
        break

if solution is not None:
    print("\nFinal solution:", solution)
    print("Final cost:", calculate_cost(solution))