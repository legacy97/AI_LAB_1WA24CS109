def calculate_cost(state):
    n = len(state)
    conflicts = 0

    for i in range(n):
        for j in range(i + 1, n):
            # Same row or same diagonal
            if (state[i] == state[j] or
                    abs(state[i] - state[j]) == abs(i - j)):
                conflicts += 1

    return conflicts


def hill_climbing():
    state = [3, 1, 2, 0]

    print("Initial state:", state)
    print("Initial cost:", calculate_cost(state))

    while True:
        current_cost = calculate_cost(state)
        best_state = state[:]
        best_cost = current_cost
        best_pair = None

        # Generate neighbors by swapping pairs of queens.
        # Iteration order ensures smallest-index tie-breaking.
        for i in range(len(state)):
            for j in range(i + 1, len(state)):
                neighbor = state[:]
                neighbor[i], neighbor[j] = neighbor[j], neighbor[i]

                cost = calculate_cost(neighbor)
                print(f"Swap ({i}, {j}): {neighbor}, Cost = {cost}")

                if cost < best_cost:
                    best_cost = cost
                    best_state = neighbor
                    best_pair = (i, j)

        # Stop if no better neighbor exists.
        if best_cost >= current_cost:
            print("No better neighbor found. Terminating.")
            break

        state = best_state
        print("Selected swap:", best_pair)
        print("Next state:", state)
        print("Next cost:", best_cost)
        print()

        if best_cost == 0:
            print("Goal state reached!")
            break

    print("Final state:", state)
    print("Final cost:", calculate_cost(state))


hill_climbing()