from itertools import product

# Implication function
def implies(a, b):
    return not a or b

# Knowledge Base
def KB(P, Q, R):
    return (implies(Q, P) and
            implies(P, not Q) and
            (Q or R))

# Truth Table Enumeration Algorithm
def TT_Entails(query):
    for P, Q, R in product([True, False], repeat=3):

        if KB(P, Q, R):
            if not query(P, Q, R):
                return False

    return True


# Display Truth Table
print("P Q R | Q->P | P->~Q | Q|R | KB")
print("-----------------------------------")

for P, Q, R in product([True, False], repeat=3):

    s1 = implies(Q, P)
    s2 = implies(P, not Q)
    s3 = Q or R
    kb = KB(P, Q, R)

    print(f"{int(P)} {int(Q)} {int(R)} |"
          f"  {int(s1)}   |"
          f"   {int(s2)}   |"
          f"  {int(s3)}  |"
          f" {int(kb)}")


# Queries given in PPT
print("\nEntailment Results:")

# Query 1: KB entails R
print("KB entails R:",
      TT_Entails(lambda P, Q, R: R))

# Query 2: KB entails R -> P
print("KB entails R -> P:",
      TT_Entails(lambda P, Q, R: implies(R, P)))

# Query 3: KB entails Q -> R
print("KB entails Q -> R:",
      TT_Entails(lambda P, Q, R: implies(Q, R)))