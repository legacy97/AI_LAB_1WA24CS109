# First Order Logic - Forward Chaining

# Initial Knowledge Base (Facts)
KB = {
    ("American", "Robert"),
    ("Enemy", "A", "America"),
    ("Owns", "A", "T1"),
    ("Missile", "T1")
}

# Forward Chaining Algorithm
def forward_chaining(KB):

    inferred = True

    while inferred:
        inferred = False
        new_facts = set()

        # Rule 1: Enemy(x, America) -> Hostile(x)
        for fact in KB:
            if fact[0] == "Enemy" and fact[2] == "America":
                new_facts.add(("Hostile", fact[1]))

        # Rule 2: Missile(x) -> Weapon(x)
        for fact in KB:
            if fact[0] == "Missile":
                new_facts.add(("Weapon", fact[1]))

        # Rule 3: Missile(x) AND Owns(A, x)
        #         -> Sells(Robert, x, A)
        for fact1 in KB:
            for fact2 in KB:
                if (fact1[0] == "Missile" and
                    fact2[0] == "Owns" and
                    fact1[1] == fact2[2] and
                    fact2[1] == "A"):

                    new_facts.add(
                        ("Sells", "Robert", fact1[1], "A")
                    )

        # Rule 4: Crime rule
        # American(p) AND Weapon(q) AND
        # Sells(p,q,r) AND Hostile(r) -> Criminal(p)

        for fact1 in KB:
            if fact1[0] == "American":

                for fact2 in KB:
                    if fact2[0] == "Weapon":

                        for fact3 in KB:
                            if fact3[0] == "Sells":

                                for fact4 in KB:
                                    if fact4[0] == "Hostile":

                                        if (fact1[1] == fact3[1] and
                                            fact2[1] == fact3[2] and
                                            fact4[1] == fact3[3]):

                                            new_facts.add(
                                                ("Criminal", fact1[1])
                                            )

        # Add newly inferred facts
        if not new_facts.issubset(KB):
            KB.update(new_facts)
            inferred = True

    return KB


# Execute Forward Chaining
KB = forward_chaining(KB)

# Display all inferred facts
print("Knowledge Base after Forward Chaining:")
for fact in sorted(KB):
    print(fact)

# Check the query
query = ("Criminal", "Robert")

print("\nQuery:", query)

if query in KB:
    print("TRUE - Robert is a Criminal")
else:
    print("FALSE - Robert is not proved to be a Criminal")

